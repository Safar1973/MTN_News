/* تفعيل رابط الكاتيجوري */
function setActiveCategoryLink(activeLink) {
    document
        .querySelectorAll(".category-list a")
        .forEach(a => a.classList.remove("active"));
    if (activeLink) activeLink.classList.add("active");
}

/* عرض المنتجات */
function renderProducts(filter = "all") {
    const grid = document.getElementById("product-grid");
    grid.innerHTML = "";

    const t = translations[currentLang];

    const filtered =
        filter === "all"
            ? products
            : products.filter(p => p.category === filter);

    filtered.forEach(p => {
        const card = document.createElement("div");
        card.className = "product-card";
        card.onclick = () => showModal(p);

        card.innerHTML = `
            <img src="${p.img}" alt="${p.names[currentLang]}" class="product-image">
            <div class="product-info">
                <div class="product-title">${p.names[currentLang]}</div>
                <div class="product-price">${p.price.toFixed(2)} ${t.currency
            }</div>
            </div>
        `;
        grid.appendChild(card);
    });
}

/* Modal المنتج */
function showModal(product) {
    const modal = document.getElementById("product-modal");
    const t = translations[currentLang];

    document.getElementById("modal-img").src = product.img;
    document.getElementById("modal-title").textContent =
        product.names[currentLang];
    document.getElementById("modal-price").textContent =
        product.price.toFixed(2) + " " + t.currency;

    const details = document.getElementById("modal-details-content");
    details.innerHTML = `
        <div class="detail-row"><span>${t.expiry}:</span> <span>${product.expiry
        }</span></div>
        <div class="detail-row"><span>${t.delivery}:</span> <span>${t.deliveryTime
        }</span></div>
        <div class="detail-row"><span>${t.payment}:</span> <span>${t.buyInfo
        }</span></div>
    `;

    const modalBtn = document.getElementById("modal-btn");
    modalBtn.textContent = t.addToCart;
    modalBtn.onclick = () => addToCart(product);

    modal.style.display = "flex";
}

function closeModal() {
    document.getElementById("product-modal").style.display = "none";
}

/* Cart functions */
function addToCart(product) {
    const existing = cart.find(item => item.product.id === product.id);
    if (existing) {
        existing.qty += 1;
    } else {
        cart.push({ product, qty: 1 });
    }
    updateCartUI();
    updateOrderSummary();
    closeModal();
}

/* زيادة / إنقاص كمية منتج في السلة */
function changeQty(productId, delta) {
    const item = cart.find(i => i.product.id === productId);
    if (!item) return;

    item.qty += delta;
    if (item.qty <= 0) {
        // حذف المنتج بالكامل لو أصبحت الكمية 0
        cart = cart.filter(i => i.product.id !== productId);
    }
    updateCartUI();
    updateOrderSummary();
}

/* حذف منتج واحد من السلة كلياً */
function removeItem(productId) {
    cart = cart.filter(i => i.product.id !== productId);
    updateCartUI();
    updateOrderSummary();
}

/* تفريغ السلة بالكامل */
function clearCart() {
    cart = [];
    updateCartUI();
    updateOrderSummary();
}

/* تحديث واجهة السلة */
function updateCartUI() {
    const t = translations[currentLang];

    const countEl = document.getElementById("cart-count");
    const itemsContainer = document.getElementById("cart-items");
    const totalEl = document.getElementById("cart-total");

    if (!itemsContainer) return;

    const totalItems = cart.reduce((sum, item) => sum + item.qty, 0);
    if (countEl) countEl.textContent = totalItems;

    itemsContainer.innerHTML = "";

    if (cart.length === 0) {
        itemsContainer.innerHTML = `<p class="cart-empty">${t.cartEmpty}</p>`;
        totalEl.textContent = `0.00 ${t.currency}`;
        return;
    }

    let total = 0;

    cart.forEach(item => {
        const row = document.createElement("div");
        row.className = "cart-item";

        const lineTotal = item.product.price * item.qty;
        total += lineTotal;

        row.innerHTML = `
            <div class="cart-item-info">
                <span class="cart-item-title">${item.product.names[currentLang]
            }</span>
                <span class="cart-item-qty">x${item.qty}</span>
                <div class="cart-item-controls">
                    <button class="qty-btn" onclick="changeQty(${item.product.id}, -1)">-</button>
                    <button class="qty-btn" onclick="changeQty(${item.product.id}, 1)">+</button>
                    <button class="remove-item-btn" onclick="removeItem(${item.product.id})">🗑</button>
                </div>
            </div>
            <div class="cart-item-price">${lineTotal.toFixed(2)} ${t.currency
            }</div>
        `;
        itemsContainer.appendChild(row);
    });

    totalEl.textContent = `${total.toFixed(2)} ${t.currency}`;
}

/* فتح / إغلاق السلة */
function toggleCart() {
    const panel = document.getElementById("cart-panel");
    panel.classList.toggle("open");
}

/* فتح صفحة الدفع من زر Checkout */
function openCheckout() {
    // لو السلة فارغة لا نذهب إلى الدفع
    if (cart.length === 0) {
        alert(translations[currentLang].cartEmpty);
        return;
    }
    toggleCart();
    goToSection("checkout-section");
}

/* تحديث ملخص الطلب في صفحة الدفع */
function updateOrderSummary() {
    const t = translations[currentLang];
    const container = document.getElementById("order-summary-items");
    const totalEl = document.getElementById("order-total-value");
    if (!container) return;

    container.innerHTML = "";

    if (cart.length === 0) {
        container.innerHTML = `<p class="cart-empty">${t.cartEmpty}</p>`;
        totalEl.textContent = `0.00 ${t.currency}`;
        return;
    }

    let total = 0;
    cart.forEach(item => {
        const lineTotal = item.product.price * item.qty;
        total += lineTotal;
        const div = document.createElement("div");
        div.className = "checkout-summary-item";
        div.innerHTML = `
            <span>${item.product.names[currentLang]} x${item.qty}</span>
            <span>${lineTotal.toFixed(2)} ${t.currency}</span>
        `;
        container.appendChild(div);
    });

    totalEl.textContent = `${total.toFixed(2)} ${t.currency}`;
}

/* ارسال الطلب (تجريبي) */
function submitOrder(e) {
    e.preventDefault();
    const t = translations[currentLang];
    if (cart.length === 0) {
        alert(t.cartEmpty);
        return;
    }

    alert(t.orderPlacedMsg);
    // ممكن هنا لاحقاً تربطها بباك-إند أو خدمة حقيقية
}

/* التنقل بين الصفحات (Home / Products / About / Checkout) */
function goToSection(sectionId) {
    document
        .querySelectorAll(".page-section")
        .forEach(sec => sec.classList.remove("active"));
    const target = document.getElementById(sectionId);
    if (target) target.classList.add("active");

    // تفعيل الرابط في الترويسة
    document
        .querySelectorAll(".nav-links a")
        .forEach(a => a.classList.remove("active-link"));

    if (sectionId === "home-section") {
        document
            .getElementById("nav-home")
            .classList.add("active-link");
    } else if (sectionId === "products-section") {
        document
            .getElementById("nav-products")
            .classList.add("active-link");
    } else if (sectionId === "about-section") {
        document
            .getElementById("nav-about")
            .classList.add("active-link");
    }
}

/* ربط الروابط في الـ header */
function setupNavLinks() {
    document.querySelectorAll(".nav-links a").forEach(link => {
        link.addEventListener("click", e => {
            e.preventDefault();
            const sectionId = link.getAttribute("data-section");
            if (sectionId) {
                goToSection(sectionId);
            }
        });
    });
}

/* إغلاق المودال عند الضغط خارج */
window.onclick = function (event) {
    const modal = document.getElementById("product-modal");
    if (event.target === modal) {
        closeModal();
    }
};

/* Initialize */
document.addEventListener("DOMContentLoaded", () => {
    setupNavLinks();
    goToSection("home-section");
    setLanguage("de"); // اللغة الافتراضية
});
